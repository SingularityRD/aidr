export function renderPrintableReport(report: ComplianceReport, language: PrintLanguage): string {
	const labels = PRINT_LABELS[language];
	const profile = report.sections.tenant_profile;
	const signature = report.integrity.signature;
	const statement = language === "en" ? report.statement : labels.statement;
	const limitations = report.limitations.map((text) => labels.limitations[text] ?? text);
	const sections = COMPLIANCE_SECTION_KEYS.map((key) => {
		const meta = labels.sections[key];
		const body = sectionBlocks(report.sections[key])
			.map((block) => renderBlock(labels, block))
			.join("");
		return `<section><h2>${escapeHtml(meta.title)}</h2><p class="proves">${escapeHtml(meta.proves)}</p>${body}</section>`;
	}).join("");
	const meta: Array<[string, string]> = [
		[labels.tenant, `${String(profile.name ?? "")} (${String(profile.tenant_id ?? "")})`],
		[labels.period, `${report.period.from} – ${report.period.to}`],
		[labels.generated, report.generated_at],
		[labels.generatedBy, `${report.generated_by.user_id} (${report.generated_by.role})`],
		[labels.reportId, report.report_id],
		[labels.sha256, report.integrity.sha256],
		[labels.signature, signature ? labels.signed(signature.key_id) : labels.unsigned],
	];
	return `<!doctype html>
<html lang="${language}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(`${labels.title} - ${String(profile.name ?? "")}`)}</title>
<style>${STYLE}</style>
</head>
<body>
<header>
<h1>${escapeHtml(labels.title)}</h1>
<p class="subtitle">${escapeHtml(labels.subtitle)}</p>
<dl class="meta">${meta.map(([term, value]) => `<dt>${escapeHtml(term)}</dt><dd>${escapeHtml(value)}</dd>`).join("")}</dl>
<p class="note">${escapeHtml(labels.derivedNote)} <code>${escapeHtml(labels.verify)}</code></p>
</header>
<h2>${escapeHtml(labels.statementTitle)}</h2>
<p class="statement">${escapeHtml(statement)}</p>
${sections}
<h2>${escapeHtml(labels.limitationsTitle)}</h2>
<ul>${limitations.map((text) => `<li>${escapeHtml(text)}</li>`).join("")}</ul>
</body>
</html>
`;
}
