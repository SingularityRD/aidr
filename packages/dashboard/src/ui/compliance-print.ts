export const PRINT_LABELS: Readonly<Record<PrintLanguage, Labels>> = { en: EN, tr: TR };

function escapeHtml(value: string): string {
	return value
		.replaceAll("&", "&amp;")
		.replaceAll("<", "&lt;")
		.replaceAll(">", "&gt;")
		.replaceAll('"', "&quot;")
		.replaceAll("'", "&#39;");
}

function keyLabel(labels: Labels, path: string): string {
	return path
		.split(".")
		.map((part) => labels.keys[part] ?? part.replaceAll("_", " "))
		.join(" › ");
}

function cellText(labels: Labels, value: Cell): string {
	if (value === null || value === "none") return labels.none;
	if (value === true) return labels.yes;
	if (value === false) return labels.no;
	return String(value);
}

function renderBlock(labels: Labels, block: SectionBlock): string {
	const caption = block.path ? `<h3>${escapeHtml(keyLabel(labels, block.path))}</h3>` : "";
	const headers =
		block.kind === "fields"
			? [labels.field, labels.value]
			: block.headers.map((header) => keyLabel(labels, header));
	const rows = block.rows
		.map((row) => {
			const cells = row.map((cell, index) =>
				block.kind === "fields" && index === 0
					? keyLabel(labels, String(cell))
					: cellText(labels, cell),
			);
			return `<tr>${cells.map((cell) => `<td>${escapeHtml(cell)}</td>`).join("")}</tr>`;
		})
		.join("");
	return `${caption}<table><thead><tr>${headers.map((header) => `<th>${escapeHtml(header)}</th>`).join("")}</tr></thead><tbody>${rows}</tbody></table>`;
}

