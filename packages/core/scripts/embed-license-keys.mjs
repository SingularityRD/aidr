#!/usr/bin/env node
/**
 * Embed the license public-key registry into the core build.
 *
 * Reads `deploy/onprem/license-public-keys.json` (the `aidr-license-public-keys-v1`
 * trust root for vendor-signed licenses and customer packets) and writes
 * `src/generated/license-public-keys.ts`. The endpoint verifier
 * (`src/customer-license/verify.ts`) uses this embedded copy by default, so the registry
 * an installed endpoint trusts is part of the compiled, integrity-signed release
 * rather than a loose file that could be swapped next to it.
 *
 * Only `format`, `schema_version` and `keys` are embedded. The shipped registry
 * is intentionally empty, which verifies nothing (fail closed); a vendor release
 * build replaces the registry file before building.
 *
 * Usage: node scripts/embed-license-keys.mjs [--check]
 *   --check exits non-zero when the embedded copy differs from the registry.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(packageRoot, "..", "..", "deploy", "onprem", "license-public-keys.json");
const target = join(packageRoot, "src", "generated", "license-public-keys.ts");

function fail(message) {
	console.error(`[core] ${message}`);
	process.exit(1);
}

let registry;
try {
	registry = JSON.parse(readFileSync(source, "utf8"));
} catch {
	fail(`license public-key registry ${source} is missing or not JSON`);
}
if (
	!registry ||
	registry.format !== "aidr-license-public-keys-v1" ||
	registry.schema_version !== 1 ||
	!Array.isArray(registry.keys)
) {
	fail(`${source} is not an aidr-license-public-keys-v1 registry`);
}
// A private key must never be embedded, whatever the registry file says.
if (JSON.stringify(registry.keys).includes("PRIVATE KEY")) fail(`${source} contains private key material`);

const embedded = { format: registry.format, schema_version: registry.schema_version, keys: registry.keys };
const contents = `// Generated by packages/core/scripts/embed-license-keys.mjs from
// deploy/onprem/license-public-keys.json. Do not edit: edit the registry and rebuild.
export const EMBEDDED_LICENSE_PUBLIC_KEYS: unknown = ${JSON.stringify(embedded, null, "\t")};
`;

let current = "";
try {
	current = readFileSync(target, "utf8");
} catch {
	// Missing counts as drift.
}
if (process.argv.includes("--check")) {
	if (current !== contents) {
		fail("src/generated/license-public-keys.ts is out of date; run node packages/core/scripts/embed-license-keys.mjs");
	}
	console.log("[core] embedded license public keys match deploy/onprem/license-public-keys.json");
} else if (current !== contents) {
	writeFileSync(target, contents);
	console.log(`[core] embedded ${registry.keys.length} license public key(s) into src/generated/license-public-keys.ts`);
}
