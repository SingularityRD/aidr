import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Regenerate `src/toxic-flow-capabilities.data.ts`, the core's embedded copy of
 * `threats/flow/capabilities.yaml`. Run after editing the YAML:
 *
 *   node packages/core/scripts/embed-flow-capabilities.mjs
 *
 * `--check` exits non-zero when the embedded copy has drifted from the YAML
 * (the core test suite performs the same check).
 */

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(packageRoot, "..", "..", "threats", "flow", "capabilities.yaml");
const target = join(packageRoot, "src", "toxic-flow-capabilities.data.ts");

const yaml = readFileSync(source, "utf8");
const contents = `// Generated by packages/core/scripts/embed-flow-capabilities.mjs from
// threats/flow/capabilities.yaml. Do not edit: edit the YAML and regenerate.
export const EMBEDDED_FLOW_CAPABILITIES_YAML: string =
	${JSON.stringify(yaml)};
`;

if (process.argv.includes("--check")) {
	let current = "";
	try {
		current = readFileSync(target, "utf8");
	} catch {
		// Missing counts as drift.
	}
	if (current !== contents) {
		console.error(
			"[core] src/toxic-flow-capabilities.data.ts is out of date; run node packages/core/scripts/embed-flow-capabilities.mjs",
		);
		process.exit(1);
	}
	console.log("[core] embedded toxic-flow capability data matches threats/flow/capabilities.yaml");
} else {
	writeFileSync(target, contents);
	console.log("[core] wrote src/toxic-flow-capabilities.data.ts");
}
