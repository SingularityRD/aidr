#!/usr/bin/env node
/**
 * Pre-parse the shipped threat YAML into `src/generated/threat-parse-cache.ts`.
 *
 * Why: a hook is a fresh process per tool call, so the `yaml` parser runs cold
 * (no JIT warm-up) over ~350 rules every time. Measured on a quiet Windows 11
 * machine that was ~110 ms of a ~340 ms hook, the single largest cost. JSON-like
 * data embedded in the bundle is parsed in a couple of milliseconds instead.
 *
 * Safety model: the cache is keyed by the SHA-256 of each YAML file's exact
 * content. `loadThreats` still reads every YAML file from disk and only uses a
 * cached entry when the hash matches, so the YAML stays authoritative: an edited,
 * user-supplied or newer file simply misses the cache and is parsed as before.
 * The cache can therefore never make a rule disappear or change.
 *
 * The parse step here must stay equivalent to `parseThreatYaml` in
 * `src/threat-loader.ts`; `threat-parse-cache.test.ts` asserts that.
 *
 * Usage: node scripts/compile-threat-cache.mjs [--check]
 */

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(scriptDir, "..");
const threatsDir = resolve(packageRoot, "..", "..", "threats");
const outFile = join(packageRoot, "src", "generated", "threat-parse-cache.ts");

/** Line endings are normalised so a CRLF checkout hashes like the LF source. */
function contentHash(content) {
	return createHash("sha256").update(content.replace(/\r\n/g, "\n"), "utf8").digest("hex");
}

function yamlFilesIn(dir) {
	try {
		return readdirSync(dir)
			.filter((f) => f.endsWith(".yaml"))
			.sort()
			.map((f) => join(dir, f));
	} catch {
		return [];
	}
}

function parseThreatYaml(content) {
	try {
		return parseYaml(content);
	} catch {
		return parseYaml(content.replace(/\\(?=[.*+?^$()\[\]{}|\\])/g, "\\\\"));
	}
}

const entries = {};
for (const name of readdirSync(threatsDir)
	.filter((f) => f.endsWith(".yaml"))
	.sort()) {
	const content = readFileSync(join(threatsDir, name), "utf-8");
	const data = parseThreatYaml(content);
	if (!Array.isArray(data)) continue;
	// Line endings are normalised so a CRLF checkout hashes like the LF source.
	entries[contentHash(content)] = data;
}

/**
 * Other shipped YAML data read on every hook call: the framework mappings
 * (~40 KB, the largest single YAML parse left on the per-call path), the
 * toxic-flow capability patterns and the allowlists. Same safety model: keyed
 * by content hash, consulted only through `parseShippedYaml`, and any other
 * content is parsed normally.
 */
const dataEntries = {};
const allowlistsDir = resolve(packageRoot, "..", "..", "allowlists");
const dataFiles = [
	...yamlFilesIn(join(threatsDir, "mappings")),
	...yamlFilesIn(join(threatsDir, "flow")),
	...yamlFilesIn(allowlistsDir),
	...yamlFilesIn(join(allowlistsDir, "model-sources")),
];
for (const file of dataFiles) {
	const content = readFileSync(file, "utf-8");
	let data;
	try {
		data = parseYaml(content);
	} catch {
		continue;
	}
	if (data === null || typeof data !== "object") continue;
	dataEntries[contentHash(content)] = data;
}

const body = `/**
 * GENERATED by scripts/compile-threat-cache.mjs - do not edit by hand.
 * Pre-parsed threat YAML keyed by the SHA-256 of each file's exact content.
 * See that script for the safety model (YAML on disk stays authoritative).
 */
export const THREAT_PARSE_CACHE: Readonly<Record<string, readonly unknown[]>> = ${JSON.stringify(entries)};

/** Pre-parsed shipped YAML data files (mappings, flow capabilities, allowlists), same keying. */
export const DATA_PARSE_CACHE: Readonly<Record<string, unknown>> = ${JSON.stringify(dataEntries)};
`;

if (process.argv.includes("--check")) {
	let current = "";
	try {
		current = readFileSync(outFile, "utf-8");
	} catch {}
	if (current !== body) {
		console.error("[core] threat-parse-cache.ts is stale; run node scripts/compile-threat-cache.mjs");
		process.exit(1);
	}
} else {
	writeFileSync(outFile, body);
	console.log(
		`[core] wrote threat parse cache (${Object.keys(entries).length} rule files, ${Object.keys(dataEntries).length} data files)`,
	);
}
