const MESSAGES: Record<Lang, Record<MessageKey, string>> = { en, tr };

/** Turkish when the preference or the system locale says so; English otherwise. */
export function resolveLanguage(preference: LanguagePref, systemLocales: readonly string[]): Lang {
	if (preference === "tr" || preference === "en") return preference;
	const first = systemLocales.find((locale) => typeof locale === "string" && locale.length > 0);
	return first?.toLowerCase().startsWith("tr") ? "tr" : "en";
}

export function translate(
	lang: Lang,
	key: MessageKey,
	params: Record<string, string | number> = {},
): string {
	const template = MESSAGES[lang][key] ?? en[key];
	return template.replace(/\{(\w+)\}/g, (match, name: string) =>
		name in params ? String(params[name]) : match,
	);
}

export function allKeys(lang: Lang): MessageKey[] {
	return Object.keys(MESSAGES[lang]) as MessageKey[];
}
