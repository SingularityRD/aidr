/**
 * Rule-data directory resolution for the SDK.
 *
 * ── Why this module exists ──────────────────────────────────────────────────
 *
 * The SDK must load real threat rules and allowlists at `init()` time. Two
 * things make that harder than it looks:
 *
 *   - `@singularityrd/aidr-core` publishes only `dist/**` — it does not ship the
 *     YAML rule data — so a published SDK cannot read the rules out of core.
 *   - `process.cwd()` is the *consumer's* working directory, never the SDK's.
 *     Loading `"threats"` relative to the cwd therefore works in the monorepo
 *     and throws for every packaged consumer.
 *
 * So the SDK ships its own copy of `threats/` and `allowlists/` under
 * `resources/` (generated by `scripts/sync-assets.mjs` during the build, the
 * same convention `packages/cli` and `packages/opencode` use) and resolves them
 * relative to the RUNNING MODULE.
 *
 * ── Resolution order (first usable candidate wins, per directory) ────────────
 *
 *   1. `AIDR_THREATS_DIR` / `AIDR_ALLOWLISTS_DIR` — explicit override, the same
 *      variable names core and the connectors already use. An override is
 *      authoritative: if it is set but unusable this is a hard error rather than
 *      a silent fall-through to the bundled copy, because silently ignoring an
 *      operator's configured rule path is how an install ends up inspecting
 *      different rules than the operator believes.
 *   2. `<moduleDir>/resources/<kind>` — resources sitting next to the runtime
 *      bundle (`dist/index.mjs`).
 *   3. `<moduleDir>/../resources/<kind>` — packaged install, where the bundle
 *      lives in `<packageRoot>/dist/` and the data in `<packageRoot>/resources/`.
 *   4. Source-tree walk-up (up to {@link MAX_WALK_UP} levels): a directory that
 *      contains BOTH `threats/` and `allowlists/` side by side. This is the
 *      monorepo checkout running from source (repository root), or a workspace
 *      build that ran before `sync-assets`. Requiring the pair keeps an
 *      unrelated `threats/` folder somewhere up the tree from being mistaken for
 *      the shipped data set.
 *   5. `<cwd>/<kind>` — legacy cwd-relative layout, kept last so embedders that
 *      vendor their own rules next to their app keep working.
 *
 * The user's `~/.singularity-aidr/threats` overlay is deliberately NOT a
 * candidate: loading it *instead of* the shipped rules would replace the whole
 * rule set with a partial one, which is the silent-degradation failure this
 * module exists to prevent. Merging overlays is core's `loadThreatsFromDirs`
 * job (`context.userThreatsDir`), not the SDK's.
 *
 * When nothing is usable, {@link resolveDataDirs} throws
 * {@link AIDRDataDirError} naming every path it looked in. `AIDRClient.init()`
 * turns that into an explicit initialisation failure — never a client that
 * "works" while detecting nothing.
 */

import { statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** The two data directories the SDK needs at `init()` time. */
export type AssetKind = "threats" | "allowlists";

/** Environment override per kind (names shared with core/connectors). */
const ENV_VARS: Record<AssetKind, string> = {
	threats: "AIDR_THREATS_DIR",
	allowlists: "AIDR_ALLOWLISTS_DIR",
};

const ALL_KINDS: readonly AssetKind[] = ["threats", "allowlists"];

/** How far up from the module directory the source-tree walk-up looks. */
const MAX_WALK_UP = 6;

/** Which candidate matched, for logging and diagnostics. */
export type DataDirSource = "env" | "bundled" | "package" | "source-tree" | "cwd";

interface Candidate {
	path: string;
	source: DataDirSource;
	/** For walk-up candidates: a sibling directory that must exist too. */
	sibling?: string;
}

export interface DataDirResolution {
	threatsDir: string;
	allowlistsDir: string;
	/** Which candidate produced each directory. */
	sources: Record<AssetKind, DataDirSource>;
	/** Every path considered for each kind, in order (useful in errors/logs). */
	searchedPaths: Record<AssetKind, string[]>;
}

export interface DataDirOptions {
	/** Module directory to resolve from. Defaults to this module's directory. */
	moduleDir?: string;
	/** Working directory used for the legacy cwd candidate. Defaults to `process.cwd()`. */
	cwd?: string;
	/** Environment to read overrides from. Defaults to `process.env`. */
	env?: Record<string, string | undefined>;
}

/**
 * Directory this module was loaded from.
 *
 * This module is bundled into both an ESM (`dist/index.mjs`) and a CommonJS
 * (`dist/index.cjs`) file. In the CommonJS bundle `import.meta` is empty
 * (esbuild emits `empty-import-meta`) while `__dirname` is the bundle's
 * directory, so `__dirname` is checked FIRST — the same idiom core's
 * `aig-infra-scan.ts` uses for exactly this reason. `import.meta.url` is the ESM
 * branch; the cwd is only the last-resort fallback when neither is available.
 */
function moduleDirectory(): string {
	if (typeof __dirname !== "undefined" && __dirname) return __dirname;
	try {
		if (typeof import.meta.url === "string") {
			return dirname(fileURLToPath(import.meta.url));
		}
	} catch {
		// `import.meta.url` is not a usable URL here; fall through to the cwd.
	}
	return process.cwd();
}

function isDirectory(candidate: string): boolean {
	try {
		return statSync(candidate).isDirectory();
	} catch {
		return false;
	}
}

function isUsable(candidate: Candidate): boolean {
	if (!isDirectory(candidate.path)) return false;
	if (candidate.sibling !== undefined && !isDirectory(candidate.sibling)) return false;
	return true;
}

/**
 * Every candidate for one kind, in the documented order.
 */
function candidatesFor(
	kind: AssetKind,
	context: { moduleDir: string; cwd: string; env: Record<string, string | undefined> },
): Candidate[] {
	const override = context.env[ENV_VARS[kind]]?.trim();
	if (override) {
		return [{ path: resolve(override), source: "env" }];
	}

	const candidates: Candidate[] = [
		{ path: join(context.moduleDir, "resources", kind), source: "bundled" },
		{ path: join(context.moduleDir, "..", "resources", kind), source: "package" },
		...walkUpCandidates(kind, context.moduleDir),
		{ path: join(context.cwd, kind), source: "cwd" },
	];
	return candidates;
}

/**
 * Walk up from the module directory looking for a checkout/workspace root that
 * holds both data directories (`<root>/threats` + `<root>/allowlists`).
 */
function walkUpCandidates(kind: AssetKind, moduleDir: string): Candidate[] {
	const otherKind: AssetKind = kind === "threats" ? "allowlists" : "threats";
	const candidates: Candidate[] = [];
	let dir = resolve(moduleDir);
	for (let level = 0; level < MAX_WALK_UP; level++) {
		const parent = resolve(dir, "..");
		if (parent === dir) break; // filesystem root
		dir = parent;
		candidates.push({
			path: join(dir, kind),
			source: "source-tree",
			sibling: join(dir, otherKind),
		});
	}
	return candidates;
}

/**
 * Resolve the bundled `threats` and `allowlists` directories.
 *
 * @throws {AIDRDataDirError} when no usable directory exists for either kind.
 *   The error carries `searchedPaths` so a caller can report exactly where the
 *   SDK looked.
 */
export function resolveDataDirs(options: DataDirOptions = {}): DataDirResolution {
	const moduleDir = resolve(options.moduleDir ?? moduleDirectory());
	const cwd = resolve(options.cwd ?? process.cwd());
	const env = options.env ?? process.env;
	const context = { moduleDir, cwd, env };

	const resolved = new Map<AssetKind, Candidate>();
	const searchedPaths: Record<AssetKind, string[]> = { threats: [], allowlists: [] };
	const sources = {} as Record<AssetKind, DataDirSource>;

	for (const kind of ALL_KINDS) {
		const candidates = candidatesFor(kind, context);
		searchedPaths[kind] = candidates.map((candidate) => candidate.path);
		const hit = candidates.find(isUsable);
		if (!hit) {
			throw new AIDRDataDirError(kind, candidates, context);
		}
		resolved.set(kind, hit);
		sources[kind] = hit.source;
	}

	const threatsDir = resolved.get("threats")?.path;
	const allowlistsDir = resolved.get("allowlists")?.path;
	// Unreachable: the loop above throws instead of leaving a kind unresolved.
	if (threatsDir === undefined || allowlistsDir === undefined) {
		throw new AIDRDataDirError("threats", [], context);
	}

	return { threatsDir, allowlistsDir, sources, searchedPaths };
}

/**
 * The SDK could not find its rule data. Thrown by {@link resolveDataDirs} and
 * surfaced by `AIDRClient.init()`.
 *
 * This is deliberately fatal: a client without rules cannot inspect anything,
 * and a check that inspects nothing must never be reported as a clean result.
 */
export class AIDRDataDirError extends Error {
	readonly kind: AssetKind;
	/** Every path that was considered, in order. */
	readonly searchedPaths: string[];
	readonly moduleDir: string;
	readonly cwd: string;

	constructor(
		kind: AssetKind,
		candidates: Candidate[],
		context: { moduleDir: string; cwd: string },
	) {
		const searched = candidates.map((candidate) => candidate.path);
		const listed = candidates
			.map((candidate, index) => `  ${index + 1}. ${candidate.path}  [${candidate.source}]`)
			.join("\n");
		const override = ENV_VARS[kind];

		super(
			[
				`Singularity AIDR cannot initialise: no usable "${kind}" directory was found, so no threat rules could be loaded.`,
				"The AIDR SDK refuses to run without its rules: a check that inspects nothing is not a clean result.",
				"",
				`Searched for "${kind}" (in order):`,
				listed.length > 0 ? listed : "  (no candidates; unexpected)",
				"",
				`Module directory: ${context.moduleDir}`,
				`Working directory: ${context.cwd}`,
				"",
				`Fix one of: reinstall @singularityrd/aidr-sdk (its "resources" directory is missing from this install), ` +
					`set ${override} to a directory containing the rules, or run the build so resources/ is generated.`,
			].join("\n"),
		);

		this.name = "AIDRDataDirError";
		this.kind = kind;
		this.searchedPaths = searched;
		this.moduleDir = context.moduleDir;
		this.cwd = context.cwd;
	}
}

/**
 * The SDK found its rule data but could not use it (unreadable files, unparseable
 * YAML, or zero rules loaded). Thrown by `AIDRClient.init()`.
 */
export class AIDRInitError extends Error {
	/** Every rule/allowlist path that was searched, in order. */
	readonly searchedPaths: string[];

	constructor(message: string, options: { searchedPaths?: string[]; cause?: unknown } = {}) {
		super(message, options.cause === undefined ? undefined : { cause: options.cause });
		this.name = "AIDRInitError";
		this.searchedPaths = options.searchedPaths ?? [];
	}
}

/**
 * Data directories plus the module directory they were resolved from. Exposed
 * for diagnostics (health checks, doctor-style commands, tests).
 */
export function getBundledDataDirs(options: DataDirOptions = {}): DataDirResolution & {
	moduleDir: string;
} {
	const moduleDir = resolve(options.moduleDir ?? moduleDirectory());
	return { ...resolveDataDirs({ ...options, moduleDir }), moduleDir };
}
