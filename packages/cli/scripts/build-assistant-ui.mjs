#!/usr/bin/env node
/**
 * Bundle the Setup Assistant's page (src/assistant/ui: index.html, app.css,
 * app.ts, icon.svg) into `src/generated/assistant-ui.ts`, a module of plain
 * strings the CLI serves from memory.
 *
 * Why a generated module and not files next to the binary: the multi-call SEA
 * binary embeds the CLI as one bundled script, and the bundle manifest the
 * release key signs covers that binary. Strings compiled into the CLI are
 * therefore inside the signed artifact on every distribution (SEA, npm `dist/`
 * with its artifact manifest), and nothing can be swapped on disk.
 *
 * The file is committed so `tsc --noEmit` works on a fresh checkout;
 * `--check` fails when it is out of date (the assistant tests run it).
 *
 * Usage: node scripts/build-assistant-ui.mjs [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const uiDir = join(packageRoot, "src", "assistant", "ui");
const outFile = join(packageRoot, "src", "generated", "assistant-ui.ts");

export async function renderAssistantUi() {
	const esbuild = await import("esbuild");
	const result = await esbuild.build({
		entryPoints: [join(uiDir, "app.ts")],
		bundle: true,
		write: false,
		format: "iife",
		platform: "browser",
		target: ["chrome110", "edge110", "firefox115"],
		minify: true,
		legalComments: "none",
		charset: "utf8",
		logLevel: "warning",
	});
	const js = result.outputFiles[0].text;
	const read = (name) => readFileSync(join(uiDir, name), "utf8");
	const assets = { html: read("index.html"), css: read("app.css"), js, icon: read("icon.svg") };
	return [
		"// Generated by packages/cli/scripts/build-assistant-ui.mjs from src/assistant/ui. Do not edit.",
		'import type { AssistantAssets } from "../assistant/server.js";',
		"",
		`export const ASSISTANT_UI: AssistantAssets = ${JSON.stringify(assets, null, "\t")};`,
		"",
	].join("\n");
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
	const text = await renderAssistantUi();
	let current = "";
	try {
		current = readFileSync(outFile, "utf8");
	} catch {
		current = "";
	}
	if (process.argv.includes("--check")) {
		if (current !== text) {
			console.error(
				`${outFile} is out of date; run: node packages/cli/scripts/build-assistant-ui.mjs`,
			);
			process.exit(1);
		}
		console.log("Setup Assistant UI bundle is up to date.");
	} else if (current !== text) {
		writeFileSync(outFile, text);
		console.log(`Wrote ${outFile}`);
	}
}
