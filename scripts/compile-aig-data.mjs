/** Return a stable source revision.  The compiler is deterministic for a
 * pinned checkout; wall-clock time must never enter a generated artefact. */
function sourceRevision() {
  if (!existsSync(join(AIG, ".git"))) return CURRENT_RELEASE.source_commit;
  try {
    return execFileSync("git", ["-C", AIG, "rev-parse", "HEAD"], {
      cwd: ROOT,
      encoding: "utf8",
      env: sanitizedAigChildEnv(),
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return process.env.AIG_SOURCE_COMMIT || "unknown";
  }
}

// AIG_SOURCE_DATE is deliberately scoped to this corpus. The root release's
// SOURCE_DATE_EPOCH changes for every parent candidate even when the pinned AIG
// commit does not, which would make committed generated bytes perpetually dirty.
function sourceDate(commit) {
  if (!existsSync(join(AIG, ".git"))) return CURRENT_RELEASE.source_date;
  const explicit = process.env.AIG_SOURCE_DATE;
  if (explicit) {
    const parsed = new Date(explicit);
    if (!Number.isNaN(parsed.getTime())) return parsed.toISOString();
  }
  try {
    const value = execFileSync("git", ["-C", AIG, "show", "-s", "--format=%cI", commit], {
      cwd: ROOT,
      encoding: "utf8",
      env: sanitizedAigChildEnv(),
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
    return new Date(value).toISOString();
  } catch {
    return "1970-01-01T00:00:00.000Z";
  }
}

function readReleaseRegistry() {
  let registry;
  try {
    registry = JSON.parse(readFileSync(RELEASE_REGISTRY_FILE, "utf8"));
  } catch (error) {
    console.error(`[aig] Unable to read ${RELEASE_REGISTRY_FILE}: ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
  if (registry?.schema !== "aig-release-sequences/v1" || !Array.isArray(registry.releases) || registry.releases.length === 0) {
    console.error("[aig] AIG release sequence registry is invalid or empty");
    process.exit(1);
  }
  for (let index = 0; index < registry.releases.length; index++) {
    const release = registry.releases[index];
    if (
      release?.release_sequence !== index + 1 ||
      !/^[a-f0-9]{40}$/.test(release.source_commit) ||
      !/^[a-f0-9]{64}$/.test(release.bundle_id)
    ) {
      console.error(`[aig] AIG release sequence registry entry ${index + 1} is invalid`);
      process.exit(1);
    }
  }
  return registry.releases.at(-1);
}

