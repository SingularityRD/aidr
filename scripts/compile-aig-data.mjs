let signingPrivateKey = null;

function signManifest(payload) {
  if (!signingPrivateKey) return null;
  const signer = createSign("RSA-SHA256");
  signer.update(canonicalJson(payload));
  signer.end();
  return {
    algorithm: "RSA-SHA256",
    key_id: process.env.AIG_SIGNING_KEY_ID.trim(),
    value: signer.sign(signingPrivateKey, "base64"),
  };
}

function validateSigningConfiguration() {
  const privateKeyPath = process.env.AIG_SIGNING_PRIVATE_KEY_PATH?.trim();
  const inlinePrivateKey = process.env.AIG_SIGNING_PRIVATE_KEY?.trim();
  if (privateKeyPath && !existsSync(privateKeyPath)) {
    console.error(`[aig] AIG signing private key file does not exist: ${privateKeyPath}`);
    process.exit(1);
  }
  const privateKey = inlinePrivateKey ||
    (privateKeyPath ? readFileSync(privateKeyPath, "utf8") : "");
  const hasPrivateKey = Boolean(privateKey);
  const keyId = process.env.AIG_SIGNING_KEY_ID?.trim();
  if (hasPrivateKey && (!keyId || keyId.toLowerCase() === "unspecified")) {
    console.error("[aig] AIG_SIGNING_KEY_ID must identify the configured signing key; blank and 'unspecified' values are rejected");
    process.exit(1);
  }
  if (!hasPrivateKey) return;
  try {
    signingPrivateKey = createPrivateKey(privateKey);
  } catch (error) {
    console.error(`[aig] AIG signing private key is invalid: ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
  if (signingPrivateKey.asymmetricKeyType !== "rsa") {
    console.error("[aig] AIG signing private key must be RSA");
    process.exit(1);
  }
  if ((signingPrivateKey.asymmetricKeyDetails?.modulusLength ?? 0) < 2048) {
    console.error("[aig] AIG signing private key must contain at least 2048 RSA bits");
    process.exit(1);
  }
}

function buildManifest(artifacts) {
  const artifactHashes = Object.fromEntries(
    Object.entries(artifacts).map(([name, data]) => [name, {
      sha256: sha256(data),
      bytes: Buffer.byteLength(data),
    }]),
  );
  const bundleId = sha256(canonicalJson(artifactHashes));
  if (CURRENT_RELEASE.source_commit !== SOURCE_COMMIT || CURRENT_RELEASE.bundle_id !== bundleId) {
    console.error(
      `[aig] Compiled corpus is not registered at release sequence ${RELEASE_SEQUENCE}; append the next reviewed entry to config/aig-release-sequence.json (source_commit=${SOURCE_COMMIT}, bundle_id=${bundleId})`,
    );
    console.error(`[aig] Candidate artifact hashes: ${JSON.stringify(artifactHashes)}`);
    process.exit(1);
  }
  const payload = {
    schema: "aig-data-manifest/v1",
    generated: GENERATED_AT,
    release_sequence: RELEASE_SEQUENCE,
    source: {
      repository: "https://github.com/SingularityRD/ai-infra-guard",
      commit: SOURCE_COMMIT,
      git_tree_oid: CURRENT_RELEASE.source_tree_oid,
      tree_sha256: sourceTreeDigest(),
    },
    bundle_id: bundleId,
    artifacts: artifactHashes,
    counts: {
      cves: JSON.parse(artifacts["aig-cve-index.json"]).cves.length,
      fingerprints: JSON.parse(artifacts["aig-fingerprints.json"]).fingerprints.length,
      mcp_categories: JSON.parse(artifacts["aig-mcp-categories.json"]).categories.length,
    },
    runtime: {
      schema: "aig-runtime-data/v1",
      root: "data",
      tree_sha256: pinnedSourceTreeDigest(RUNTIME_DATA_FILES),
      files: RUNTIME_DATA_FILES.length,
      bytes: RUNTIME_DATA_FILES.reduce((total, file) => total + file.contents.length, 0),
    },
  };
  return {
    ...payload,
    signature: signManifest(payload),
  };
}

