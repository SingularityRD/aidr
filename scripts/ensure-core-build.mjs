#!/usr/bin/env node
/**
 * Build `packages/core` only when it actually needs building.
 *
 * ## Why this exists
 *
 * Every connector's build script starts with `pnpm -C ../core build`, whose first
 * action is `rmrf dist`. In a workspace build (`pnpm build`) pnpm runs those
 * packages concurrently, so four processes delete and recreate the SAME
 * `packages/core/dist` tree at the same time. The interleaving fails the build
 * ("Build failed with 1 error", missing `dist/...` entries) and, when it happens
 * during a test run, produces the misleading
 * "Failed to resolve entry for package @singularityrd/aidr-core" (AIDR-014).
 *
 * Nothing is wrong with the connectors' dependency on core; the defect is that
 * the dependency was expressed as "rebuild core" rather than "ensure core is
 * built". This script makes it idempotent: it skips the rebuild when the emitted
 * artifacts already exist and are at least as new as every core source input.
 *
 * It is deliberately conservative - if it cannot prove freshness cheaply it
 * rebuilds, so a stale build is never silently reused.
 *
 * Usage: node scripts/ensure-core-build.mjs
 */

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, "..");
const coreDir = join(repoRoot, "packages", "core");

/** Artifacts that must exist for core to be considered built. */
const REQUIRED_OUTPUTS = [
	join(coreDir, "dist", "index.js"),
	join(coreDir, "dist", "index.d.ts"),
];

function digest(path) {
	return createHash("sha256").update(readFileSync(path)).digest("hex");
}

/** Newest mtime under `dir`, or 0 when the directory does not exist. */
function newestMtime(dir, filter) {
	if (!existsSync(dir)) return 0;
	let newest = 0;
	const walk = (current) => {
		for (const entry of readdirSync(current, { withFileTypes: true })) {
			const full = join(current, entry.name);
			if (entry.isDirectory()) {
				walk(full);
				continue;
			}
			if (filter && !filter(entry.name)) continue;
			const mtime = statSync(full).mtimeMs;
			if (mtime > newest) newest = mtime;
		}
	};
	walk(dir);
	return newest;
}

function needsBuild() {
	for (const output of REQUIRED_OUTPUTS) {
		if (!existsSync(output)) return "a required output is missing";
	}
	// fs.cp preserves the source JSON mtime on some hosts. Compare the actual
	// generated bytes instead of treating an old copied timestamp as stale JS.
	const generatedSource = join(coreDir, "src", "generated");
	const generatedOutput = join(coreDir, "dist", "generated");
	if (!existsSync(generatedSource) || !existsSync(generatedOutput)) return "generated data is missing";
	const generatedFiles = readdirSync(generatedSource).filter((name) => name.endsWith(".json"));
	if (generatedFiles.length === 0) return "generated data is empty";
	for (const name of generatedFiles) {
		const output = join(generatedOutput, name);
		if (!existsSync(output) || digest(join(generatedSource, name)) !== digest(output)) {
			return `generated data is missing or changed: ${name}`;
		}
	}

	// Compare against the inputs that determine the emitted JavaScript.
	//
	// Only `.ts` counts: `src/generated/*.json` is data that core COPIES into
	// dist, and core's own compile step may rewrite it after tsc has run, which
	// made the generated JSON look newer than the build output and defeated the
	// freshness check.
	const sourceDir = join(coreDir, "src");
	const sourceMtime = newestMtime(sourceDir, (name) => name.endsWith(".ts"));
	const configMtime = existsSync(join(coreDir, "tsconfig.json"))
		? statSync(join(coreDir, "tsconfig.json")).mtimeMs
		: 0;
	const inputMtime = Math.max(sourceMtime, configMtime);

	// Compiled JS/declarations must be fresh relative to TypeScript sources.
	let oldestOutput = Number.POSITIVE_INFINITY;
	for (const output of REQUIRED_OUTPUTS) {
		oldestOutput = Math.min(oldestOutput, statSync(output).mtimeMs);
	}
	if (inputMtime === 0) return "no source inputs found (refusing to assume freshness)";
	if (inputMtime > oldestOutput) return "a source input is newer than the build output";
	return null;
}

const reason = needsBuild();
if (reason === null) {
	console.log("[core] up to date; skipping rebuild");
	process.exit(0);
}

// During a workspace build, core has already been built to completion by
// `scripts/build-workspace.mjs` and the remaining packages build in parallel. A
// rebuild here would `rmrf core/dist` while a sibling package is bundling it,
// which is exactly the race this guard exists to remove - and it surfaced as a
// misleading esbuild "Cannot read file: packages/core/dist/index.js" in an
// unrelated package. Refuse instead, with an accurate message.
if (process.env.AIDR_WORKSPACE_BUILD === "1") {
	console.error(
		`[core] refusing to rebuild during a workspace build (${reason}).\n` +
			"Core is built once, before the other packages, by scripts/build-workspace.mjs.\n" +
			"If core is missing or stale, build it explicitly first: pnpm --filter @singularityrd/aidr-core run build",
	);
	process.exit(1);
}

console.log(`[core] building (${reason})`);
execFileSync("pnpm", ["run", "build"], {
	cwd: coreDir,
	stdio: "inherit",
	shell: process.platform === "win32",
});
