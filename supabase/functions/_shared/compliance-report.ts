/** Validate the database evidence and assemble the report body (no integrity yet). */
export function buildComplianceReportBody(input: ComplianceReportInput): Record<string, unknown> {
	const evidence = projectField(input.evidence, COMPLIANCE_EVIDENCE_SPEC) as Evidence;
	const body = {
		schema: COMPLIANCE_REPORT_SCHEMA,
		report_id: input.reportId,
		generated_at: evidence.generated_at,
		generated_by: { user_id: input.actorUserId, role: evidence.actor_role },
		period: {
			from: input.from.toISOString(),
			to: input.to.toISOString(),
			days: Math.ceil((input.to.getTime() - input.from.getTime()) / DAY_MS),
		},
		statement: COMPLIANCE_STATEMENT,
		sections: {
			tenant_profile: evidence.tenant_profile,
			protection_coverage: evidence.protection_coverage,
			data_protection_activity: {
				browser_guard: evidence.browser_guard,
				agent_decisions: evidence.agent_decisions,
			},
			policy_inventory: {
				...evidence.policy_inventory,
				approval_settings: approvalSettings(evidence.policy_inventory),
			},
			access_identity: evidence.access_identity,
			incidents: evidence.incidents,
			ai_security_posture: evidence.ai_security_posture,
			data_flows: dataFlowsSection(),
			retention_deletion: evidence.retention_deletion,
			control_mappings: controlMappingsSection(),
		},
		limitations: [...COMPLIANCE_LIMITATIONS],
	};
	// Re-validate the assembled body against the published schema (defense in depth).
	return projectField(body, COMPLIANCE_REPORT_BODY_SPEC) as Record<string, unknown>;
}

// ── Integrity ──────────────────────────────────────────────────────────────

function canonicalize(value: unknown, path: string): unknown {
	if (value === null || typeof value === "string" || typeof value === "boolean") return value;
	if (typeof value === "number") {
		if (!Number.isFinite(value)) throw new Error(`non_finite_number:${path}`);
		return value;
	}
	if (Array.isArray(value)) return value.map((item, index) => canonicalize(item, `${path}[${index}]`));
	if (isRecord(value)) {
		const out: Record<string, unknown> = {};
		for (const key of Object.keys(value).sort()) {
			if (value[key] === undefined) throw new Error(`undefined_value:${path}.${key}`);
			out[key] = canonicalize(value[key], `${path}.${key}`);
		}
		return out;
	}
	throw new Error(`unsupported_value:${path}`);
}

/**
 * aidr-canonical-json/v1: object keys sorted by UTF-16 code units at every
 * level, arrays kept in order, no insignificant whitespace, standard JSON
 * string escaping, UTF-8 bytes. Undefined and non-finite numbers are refused.
 */
export function canonicalJson(value: unknown): string {
	return JSON.stringify(canonicalize(value, "$"));
}

function toHex(bytes: Uint8Array): string {
	return Array.from(bytes, (byte) => byte.toString(16).padStart(2, "0")).join("");
}

function toBase64(bytes: Uint8Array): string {
	let binary = "";
	for (const byte of bytes) binary += String.fromCharCode(byte);
	return btoa(binary);
}

function fromBase64(value: string) {
	const normalized = value.replace(/-/g, "+").replace(/_/g, "/");
	const padded = normalized + "=".repeat((4 - (normalized.length % 4)) % 4);
	return Uint8Array.from(atob(padded), (char) => char.charCodeAt(0));
}

async function sha256Hex(text: string): Promise<string> {
	const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(text));
	return toHex(new Uint8Array(digest));
}

/** DER SubjectPublicKeyInfo prefix for an Ed25519 key (RFC 8410). */
const ED25519_SPKI_PREFIX = Uint8Array.from([0x30, 0x2a, 0x30, 0x05, 0x06, 0x03, 0x2b, 0x65, 0x70, 0x03, 0x21, 0x00]);

export interface ComplianceSigner {
	keyId: string;
	/** Base64 of the PKCS#8 DER Ed25519 private key (same format as the entitlement key). */
	privateKeyPkcs8B64: string;
}

interface ComplianceSignature {
	algorithm: "ed25519";
	key_id: string;
	public_key_spki_b64: string;
	signed_payload: "canonical_json_utf8";
	value_b64: string;
}

export interface ComplianceIntegrity {
	canonicalization: typeof COMPLIANCE_CANONICALIZATION;
	hash_algorithm: "sha256";
	hashed_scope: "report_without_integrity";
	sha256: string;
	signature: ComplianceSignature | null;
}

export class ComplianceSigningError extends Error {}

async function signCanonical(canonical: string, signer: ComplianceSigner): Promise<ComplianceSignature> {
	try {
		const pkcs8 = fromBase64(signer.privateKeyPkcs8B64.trim());
		// Extractable only so the public half can be derived from the JWK `x`.
		const key = await crypto.subtle.importKey("pkcs8", pkcs8, { name: "Ed25519" }, true, ["sign"]);
		const jwk = await crypto.subtle.exportKey("jwk", key);
		if (typeof jwk.x !== "string") throw new Error("missing_public_key");
		const raw = fromBase64(jwk.x);
		if (raw.length !== 32) throw new Error("invalid_public_key");
		const spki = new Uint8Array(ED25519_SPKI_PREFIX.length + raw.length);
		spki.set(ED25519_SPKI_PREFIX);
		spki.set(raw, ED25519_SPKI_PREFIX.length);
		const signature = await crypto.subtle.sign("Ed25519", key, new TextEncoder().encode(canonical));
		return {
			algorithm: "ed25519",
			key_id: signer.keyId,
			public_key_spki_b64: toBase64(spki),
			signed_payload: "canonical_json_utf8",
			value_b64: toBase64(new Uint8Array(signature)),
		};
	} catch {
		throw new ComplianceSigningError("compliance_signing_failed");
	}
}

/** Hash (and optionally sign) a report body and return the complete report. */
export async function sealComplianceReport(
	body: Record<string, unknown>,
	signer: ComplianceSigner | null,
): Promise<Record<string, unknown> & { integrity: ComplianceIntegrity }> {
	if ("integrity" in body) throw new Error("report body already sealed");
	const canonical = canonicalJson(body);
	const integrity: ComplianceIntegrity = {
		canonicalization: COMPLIANCE_CANONICALIZATION,
		hash_algorithm: "sha256",
		hashed_scope: "report_without_integrity",
		sha256: await sha256Hex(canonical),
		signature: signer ? await signCanonical(canonical, signer) : null,
	};
	return { ...body, integrity };
}
