export class ComplianceEvidenceError extends Error {
	readonly path: string;
	constructor(path: string) {
		super(`compliance evidence rejected at ${path}`);
		this.path = path;
	}
}

/**
 * Copy `value` through `spec`: known fields are validated and copied, unknown
 * fields are dropped, and any invalid or missing field throws. Timestamps are
 * normalized to ISO-8601 UTC with millisecond precision.
 */
// biome-ignore lint/complexity/noExcessiveCognitiveComplexity: one exhaustive switch over the field kinds
function projectField(value: unknown, spec: FieldSpec, path = "$"): unknown {
	const nullable = "nullable" in spec && spec.nullable === true;
	if (value === null || value === undefined) {
		if (nullable) return null;
		throw new ComplianceEvidenceError(path);
	}
	switch (spec.kind) {
		case "string": {
			if (typeof value !== "string" || value.length > spec.max || /[\u0000-\u001f\u007f]/.test(value)) {
				throw new ComplianceEvidenceError(path);
			}
			if (spec.pattern && !spec.pattern.test(value)) throw new ComplianceEvidenceError(path);
			return value;
		}
		case "enum":
			if (typeof value !== "string" || !spec.values.includes(value)) throw new ComplianceEvidenceError(path);
			return value;
		case "count": {
			const numeric = typeof value === "string" && /^\d{1,15}$/.test(value) ? Number(value) : value;
			if (typeof numeric !== "number" || !Number.isSafeInteger(numeric) || numeric < 0) {
				throw new ComplianceEvidenceError(path);
			}
			return numeric;
		}
		case "number":
			if (typeof value !== "number" || !Number.isFinite(value) || value < spec.min || value > spec.max) {
				throw new ComplianceEvidenceError(path);
			}
			return value;
		case "boolean":
			if (typeof value !== "boolean") throw new ComplianceEvidenceError(path);
			return value;
		case "timestamp": {
			if (typeof value !== "string" || value.length > 40) throw new ComplianceEvidenceError(path);
			const ms = Date.parse(value);
			if (!Number.isFinite(ms)) throw new ComplianceEvidenceError(path);
			return new Date(ms).toISOString();
		}
		case "object": {
			if (!isRecord(value)) throw new ComplianceEvidenceError(path);
			const out: Record<string, unknown> = {};
			for (const [key, child] of Object.entries(spec.fields)) {
				out[key] = projectField(value[key], child, `${path}.${key}`);
			}
			return out;
		}
		case "array": {
			if (!Array.isArray(value) || value.length > spec.max) throw new ComplianceEvidenceError(path);
			return value.map((item, index) => projectField(item, spec.items, `${path}[${index}]`));
		}
		case "map": {
			if (!isRecord(value)) throw new ComplianceEvidenceError(path);
			const entries = Object.entries(value);
			if (entries.length > spec.max) throw new ComplianceEvidenceError(path);
			const out: Record<string, unknown> = {};
			for (const [key, item] of entries) {
				if (!spec.key.test(key)) throw new ComplianceEvidenceError(`${path}.${key}`);
				out[key] = projectField(item, spec.values, `${path}.${key}`);
			}
			return out;
		}
	}
}

